/** Entrant Class represents the entrants
 * is a Subclass for user and has extra personal information.
 * @param username: A Person's nickname
 * @param name: A person's personal name
 * @param profileImage: The entrant's profile picture (blank until profile images are set up)
 */
class Entrant(
    username: String = "",
    email: String = "",
    userID: String = "",
    var phoneNumber: String = "",
    var description: String = "",
    var name: String = "",
    var dateOfBirth: String = "",   // e.g. "2001-04-23"
    var wantsNotifications: Boolean = true,
    var profileImage: String = "",
): User(username, email, userID) {

    // Use Maps so User can add their own Custom lists

    /**
     * (I was gonna add your own campsites, hence the map, but I don't think I'll have time for that)
     * [campsiteLists]:         A Map of the 4 Campsite lists
     *                          1. Active Campsites:   Entrant is on the waiting list and the date is
     *                                                 in-between the lottery start/end dates
     *                          2. Reserved Campsites: Entrant has won the lottery and has a reservation
     *                          3. Past Campsites:     Reservation date has passed but the campsite is on the list
     *                          4. Waiting List:       Entrant has joined the campsite before the lottery starts
     * [messageCampsiteIDs]:    A List of CampsiteIDs (they message owners indirectly) that
     *                          an entrant can manage
     * [reservationIDs]:        A List of reservations from each reserved campsite
     */
    var campsiteLists: MutableMap<String, MutableList<String>> = mutableMapOf(
        "Active_Campsites" to mutableListOf(),
        "Reserved_Campsites" to mutableListOf(),   // Campsites the entrant actually reserved
        "Past_Campsites" to mutableListOf(),
        "Waiting_List" to mutableListOf()
    )

    var messageCampsiteIDs = mutableListOf<String>()
    var reservationIDs = mutableListOf<String>()

    // Add Campsite adds campsite to corresponding key
    fun addCampsite(key: String, campsiteID: String) {
        val list = campsiteLists[key] ?: return
        if (campsiteID !in list) {
            list.add(campsiteID)
        }
    }

    // Add new list adds a new list of campsites you can put
    fun addNewList(newKey: String) {
        if (newKey in campsiteLists.keys) {
            return
        }
        campsiteLists[newKey] = mutableListOf<String>()
    }

    // Remove campsite from a list
    fun removeCampsite(key: String, campsiteID: String) {
        if (key in campsiteLists.keys && campsiteID in campsiteLists[key]!!) {
            campsiteLists[key]!!.remove(campsiteID)
        }
    }

    // The following line was generated by Gemini in order to fix a bug, 2026-11-06
    // Prompt: I'm getting the following error while building my project.
    // The error is: Platform declaration clash: The following declarations have
    // the same JVM signature (getCampsiteLists()Ljava/util/Map;):
    // fun &lt;get-campsiteLists&gt;(): MutableMap<String, MutableList<String>>
    // defined in com.example.code.classes.Entrant fun getCampsiteLists():
    // Map<String, MutableList<String>> defined in com.example.code.classes.Entrant. Fix this issue.
    @JvmName("getCampsiteListsMap")
    fun getCampsiteLists(): Map<String, MutableList<String>> = campsiteLists

    @RequiresApi(Build.VERSION_CODES.O)
    fun rateCampsite(campsite: Campsite, newRating: Float, databaseCampsites: com.example.code.DatabaseCampsites) {
        campsite.setRating(newRating)
        databaseCampsites.updateCampsiteRating(campsite, newRating)
    }
}