package com.example.code.classes

import android.os.Build
import androidx.annotation.RequiresApi
import java.time.LocalDate
import java.time.LocalDateTime
import kotlin.random.Random

/**
 * Representation of A Campsite class For the App.
 * @param name                  Name of campsite
 * @param ownerID               Cache in Owner's ID in order to query who owns the campsite
 * @param campsiteID            Use a string in order to put it in the database
 * @param maxOccupancy          Max occupants of each campsite location (index i = coordinates[i])
 * @param rating                aggregate Rating (Out of 5), as calculated by Review and ReviewReply
 * @param coordinates           The locations of this campsite; one campsite can have several
 *                              (See Coordinates.kt)
 * @param lotteryStartDate      The Start date of the Lottery Selection (Limit to 1 start)
 * @param lotteryEndDate        The End Date of the Lottery Selection (Limit to 1 end)
 * @param vacationStartTimes    A List of available spots you can after winning the lottery.
 *                              Uses a list of pairs to allow for gaps you don't want people to
 *                              enroll in (Like 2 weeks, but disable the weekends, for example).
 *                              The Pairs are then start-end dates (left = start, right = end).
 */
class Campsite(
    private val name:               String,
    private val ownerID:            String,
    val campsiteID:                 String,

    private var maxOccupancy:       MutableList<Int>,
    private var price:              Float,
    private var rating:             Float? = null,
    private var coordinates:        MutableList<Coordinates>,
    private var detailsImage:       String? = null,
    private var thumbnailImage:     String? = null,

    private var lotteryStartDate:   LocalDateTime? = null,
    private var lotteryEndDate:     LocalDateTime? = null,
    private var vacationStartTimes: MutableList<Pair<LocalDateTime, LocalDateTime>> = mutableListOf()
) {
    /**
     * Description:         The Description of the campsite.
     * WaitingList:         The Waiting List upon people wait upon.
     * ActiveLotteryList:   People who join an active campsite. (I should combine this to WaitingList)
     * FinalList:           The People who are assigned into the campsite.
     * Rules:               Rules of the Campsite (Make its own header)
     * Reviews:             A Map of Reviews and their Corresponding replies, stored as IDs.
     */
    private var description: String = ""
    private var waitingList = mutableListOf<String>()
    private var activeLotteryList = mutableListOf<String>()
    private var finalList = mutableListOf<String>() // Use Entrant IDs instead
    private var rules = mutableListOf<String>()
    private var reviews = mutableMapOf<String, MutableList<String>>() // reviewID -> list of replyIDs

    // A bunch of getter functions generated by Sonnet 5.5
    fun getCoordinates(): List<Coordinates> = coordinates
    fun setCoordinates(locations: List<Coordinates>) { coordinates = locations.toMutableList() }

    // The first location (null if the campsite has none)
    fun getMainCoordinates(): Coordinates? = coordinates.firstOrNull()

    // "Country, Province, City" of the first location, plus how many others: "Canada, Alberta, Banff (+2 more)"
    fun getLocationSummary(): String {
        val first = getMainCoordinates()?.getLocationText() ?: return ""
        val others = coordinates.size - 1
        return if (others > 0) "$first (+$others more)" else first
    }
    fun getThumbnailImage(): String? = thumbnailImage
    fun getDetailsImage(): String? = detailsImage
    fun getReviews(): Map<String, List<String>> = reviews
    fun getName(): String = name
    fun getMaxOccupancy(): List<Int> = maxOccupancy
    fun setMaxOccupancy(perLocation: List<Int>) { maxOccupancy = perLocation.toMutableList() }

    // Max occupants of the location at [index] (0 if it has no capacity set)
    fun getOccupancyAt(index: Int): Int = maxOccupancy.getOrElse(index) { 0 }

    // Total spots across every location (the sum of each location's capacity)
    fun getTotalOccupancy(): Int = maxOccupancy.sum()

    // Capacity of the largest single location (0 if none are set)
    fun getPeakOccupancy(): Int = maxOccupancy.maxOrNull() ?: 0
    fun getStartDate(): LocalDateTime? = lotteryStartDate
    fun getEndDate(): LocalDateTime? = lotteryEndDate
    fun getOwnerID(): String = ownerID
    fun getPrice(): Float = price
    fun getRating(): Float? = rating
    fun setRating(newRating: Float?) { rating = newRating }
    fun getDescription(): String = description
    fun getFinalList(): List<String> = finalList
    fun getRules(): List<String> = rules
    fun getWaitingList(): List<String> = waitingList
    fun setWaitingList(entrantIDs: List<String>) { waitingList = entrantIDs.toMutableList() }
    fun setDescription(text: String) { description = text }
    fun setRules(newRules: List<String>) { rules = newRules.toMutableList() }
    fun addReview(reviewID: String, replyIDs: List<String> = emptyList()) {
        reviews[reviewID] = replyIDs.toMutableList()
    }
    fun getActiveLotteryList(): List<String> = activeLotteryList
    fun setActiveLotteryList(entrantIDs: List<String>) { activeLotteryList = entrantIDs.toMutableList() }
    fun setFinalList(entrantIDs: List<String>) { finalList = entrantIDs.toMutableList() }
    fun getVacationStartTimes(): List<Pair<LocalDateTime, LocalDateTime>> = vacationStartTimes
    fun setVacationStartTimes(times: List<Pair<LocalDateTime, LocalDateTime>>) {
        vacationStartTimes = times.toMutableList()
    }

    // Add entrant into the waiting list
    fun addEntrant(entrantID: String) {
        if (entrantID !in waitingList) {
            waitingList.add(entrantID)
        }
    }

    // Add entrant to an active waiting list
    fun addActiveLotteryEntrant(entrantID: String) {
        if (entrantID !in activeLotteryList) {
            activeLotteryList.add(entrantID)
        }
    }

    // Move an entrant from the waiting list to the active lottery list
    fun moveToActiveLottery(entrantID: String) {
        waitingList.remove(entrantID)
        addActiveLotteryEntrant(entrantID)
    }

    // True if today is within the lottery dates (both days included)
    @RequiresApi(Build.VERSION_CODES.O)
    fun isLotteryActive(today: LocalDate = LocalDate.now()): Boolean {
        val start = lotteryStartDate?.toLocalDate() ?: return false
        val end = lotteryEndDate?.toLocalDate() ?: return false
        return !today.isBefore(start) && !today.isAfter(end)
    }

    // Check if Entrant is in waiting list or active lottery list
    fun entrantInList(entrantID: String): Boolean {
        return entrantID in waitingList || entrantID in activeLotteryList
    }

    // Remove entrant from the waiting list, active lottery list and final list
    fun removeEntrant(entrantID: String) {
        waitingList.remove(entrantID)
        activeLotteryList.remove(entrantID)
        finalList.remove(entrantID)
    }

    // Use random numbers to generate a final list and cache it into the thing
    fun generateFinalList() {
        // One winner per spot, across all locations
        var capacity = getTotalOccupancy()

        //if more capacity than entrants, all entrants make the final list
        if(waitingList.size <= capacity){
            finalList = waitingList.toMutableList() // use .toMutableList() to create a copy instead of an alias
            waitingList.clear()
        } else {
            while (capacity != 0) {
                // use .size instead of .lastInt because the until value in kotlin ranges is exclusive
                val randomInd = Random.nextInt(0, waitingList.size)

                // add random entrant to final list, and remove from waitlist
                finalList.add(waitingList[randomInd])
                waitingList.removeAt(randomInd)
                capacity -= 1
            }
        }
    }

    fun toMap(): Map<String, Any?> = mapOf(
        "name" to name,
        "ownerID" to ownerID,
        "campsiteID" to campsiteID,
        "maxOccupancy" to maxOccupancy,
        "price" to price,
        "rating" to rating,
        "waitingList" to waitingList,
        "activeLotteryList" to activeLotteryList,
        "finalList" to finalList,
        "coordinates" to coordinates.map { it.toMap() },
        "thumbnailImage" to thumbnailImage,
        // Stored as ISO-8601 strings, like vacationStartTimes
        "lotteryStartDate" to lotteryStartDate?.toString(),
        "lotteryEndDate" to lotteryEndDate?.toString(),
        "detailsImage" to detailsImage,
        // Stored as ISO-8601 strings, since Firestore can't store LocalDateTime or Pair
        "vacationStartTimes" to vacationStartTimes.map { (start, end) ->
            mapOf("start" to start.toString(), "end" to end.toString())
        }
    )
}
