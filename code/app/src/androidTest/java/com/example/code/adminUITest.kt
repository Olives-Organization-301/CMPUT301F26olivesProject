package com.example.code

import androidx.compose.ui.test.assertIsDisplayed
import androidx.compose.ui.test.junit4.createComposeRule
import androidx.compose.ui.test.onNodeWithText
import androidx.compose.ui.test.performClick
import androidx.test.ext.junit.runners.AndroidJUnit4
import com.example.code.classes.AppState
import com.example.code.classes.Campsite
import com.example.code.classes.CampsiteOwner
import com.example.code.classes.Coordinates
import com.example.code.classes.Entrant
import org.junit.Assert.assertEquals
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
// this was generated by the prompt : in adminUITest, i need code that tests when Campsites
// or User Database is clicked that it does not make duplicates
// and displays the correct firebase names and fields
@RunWith(AndroidJUnit4::class)
class adminUITest {

    @get:Rule
    val composeTestRule = createComposeRule()

    @Test
    fun testTabSwitchingNoDuplicatesAndCorrectFirebaseFields() {
        val appState = AppState()

        // Populate initial test data
        val entrant1 = Entrant(username = "Entrant One", email = "e1@test.com", userID = "entrant_1")
        val entrant2 = Entrant(username = "Entrant Two", email = "e2@test.com", userID = "entrant_2")
        appState.entrants.addEntrant(entrant1)
        appState.entrants.addEntrant(entrant2)

        val owner1 = CampsiteOwner(username = "Owner One", email = "owner1@test.com", userID = "owner_1")
        appState.owners.addCampsiteOwner(owner1)

        val coords = Coordinates("Canada", "Alberta", -113.49, 53.54)
        val campsite1 = Campsite(
            name = "Pine River Camp",
            ownerID = "owner_1",
            campsiteID = "camp_101",
            maxOccupancy = 4,
            price = 45.0f,
            rating = 4.5f,
            capacity = 4,
            coordinates = coords,
            startDate = null,
            endDate = null
        )
        appState.campsites.addCampsite(campsite1)

        // Launch AdminMainSearchScreen composable
        composeTestRule.setContent {
            AdminMainSearchScreen(
                navController = androidx.navigation.compose.rememberNavController(),
                appState = appState
            )
        }

        composeTestRule.waitForIdle()

        // Verify "Campsites" tab button exists
        composeTestRule.onNodeWithText("Campsites").assertIsDisplayed()

        // Verify campsites list contains no duplicate campsite IDs
        val campsiteIds = appState.campsites.campsites.map { it.campsiteID }
        assertEquals("Campsite list should contain unique IDs without duplicates", campsiteIds.distinct().size, campsiteIds.size)

        // Click "User Database" tab
        composeTestRule.onNodeWithText("User Database").performClick()
        composeTestRule.waitForIdle()

        // Verify "User Database" tab button exists
        composeTestRule.onNodeWithText("User Database").assertIsDisplayed()

        // Verify entrants and owners lists have no duplicate IDs
        val entrantIds = appState.entrants.entrants.map { it.getUserID() }
        assertEquals("Entrants list should contain unique IDs without duplicates", entrantIds.distinct().size, entrantIds.size)

        val ownerIds = appState.owners.campsiteOwners.map { it.getUserID() }
        assertEquals("Owners list should contain unique IDs without duplicates", ownerIds.distinct().size, ownerIds.size)

        // Click back to "Campsites" tab and verify no duplicate entries were created
        composeTestRule.onNodeWithText("Campsites").performClick()
        composeTestRule.waitForIdle()

        val campsiteIdsAfter = appState.campsites.campsites.map { it.campsiteID }
        assertEquals("Re-clicking tab should not create duplicate campsites", campsiteIdsAfter.distinct().size, campsiteIdsAfter.size)
    }

    @Test
    fun testDeduplicationLogic() {
        val appState = AppState()

        val campsite = Campsite(
            name = "Sunny Meadows",
            ownerID = "owner_99",
            campsiteID = "camp_unique_99",
            maxOccupancy = 6,
            price = 60.0f,
            rating = 5.0f,
            capacity = 6,
            coordinates = Coordinates("Canada", "Edmonton", -113.49, 53.54),
            startDate = null,
            endDate = null
        )

        // Attempt adding the exact same campsite twice
        appState.campsites.addCampsite(campsite)
        appState.campsites.addCampsite(campsite)

        // Assert duplicate addition was prevented
        val matches = appState.campsites.campsites.filter { it.campsiteID == "camp_unique_99" }
        assertEquals("Duplicate campsite should not be added to list", 1, matches.size)
    }
}
